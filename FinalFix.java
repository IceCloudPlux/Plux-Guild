    private static void fixFile(Path file) throws IOException {
        byte[] bytes = Files.readAllBytes(file);
        
        int offset = 0;
        if (bytes.length >= 3 && bytes[0] == (byte)0xEF && bytes[1] == (byte)0xBB && bytes[2] == (byte)0xBF) {
            offset = 3;
        }
        
        String content = new String(bytes, offset, bytes.length - offset, StandardCharsets.UTF_8);
        
        content = removeBlockComments(content);
        content = removeLineComments(content);
        
        content = fixBrokenWords(content);
        
        content = content.replaceAll("\\s+", " ");
        
        content = content.replaceAll("\\b(package|import)\\s+", "\n$1 ");
        content = content.replaceAll("\\b(public|private|protected)\\s+", "\n$1 ");
        content = content.replaceAll("\\b(@Override|@EventHandler)\\b", "\n$1\n");
        content = content.replaceAll("\\b(class|extends|implements)\\b", "\n$1 ");
        
        content = content.replaceAll("\\{\\s*\\{", "{\n{");
        content = content.replaceAll("\\}\\s*\\}", "}\n}");
        
        content = formatCode(content);
        
        Files.write(file, content.getBytes(StandardCharsets.UTF_8));
        System.out.println("Fixed: " + file);
    }
    
    private static String removeBlockComments(String content) {
        StringBuilder result = new StringBuilder();
        boolean inString = false;
        boolean inChar = false;
        boolean inBlock = false;
        char prev = '\0';
        for (int i = 0; i < content.length(); i++) {
            char c = content.charAt(i);
            if (inBlock) {
                if (prev == '*' && c == '/') inBlock = false;
                prev = c;
                continue;
            }
            if (!inString && !inChar && prev == '/' && c == '*') {
                inBlock = true;
                result.deleteCharAt(result.length() - 1);
                prev = c;
                continue;
            }
            if (c == '"' && prev != '\\') inString = !inString;
            else if (c == '\'' && prev != '\\') inChar = !inChar;
            result.append(c);
            prev = c;
        }
        return result.toString();
    }
    
    private static String removeLineComments(String content) {
        StringBuilder result = new StringBuilder();
        boolean inString = false;
        boolean inChar = false;
        boolean inLine = false;
        char prev = '\0';
        for (int i = 0; i < content.length(); i++) {
            char c = content.charAt(i);
            if (inLine) {
                if (c == '\n') {
                    inLine = false;
                    result.append(c);
                }
                prev = c;
                continue;
            }
            if (!inString && !inChar && prev == '/' && c == '/') {
                inLine = true;
                result.deleteCharAt(result.length() - 1);
                prev = c;
                continue;
            }
            if (c == '"' && prev != '\\') inString = !inString;
            else if (c == '\'' && prev != '\\') inChar = !inChar;
            result.append(c);
            prev = c;
        }
        return result.toString();
    }
    
